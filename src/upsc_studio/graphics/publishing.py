"""Thumbnail, chapter timestamps, mind-map/definitions, and publishing package generator."""

from __future__ import annotations

import json
import textwrap
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

from upsc_studio.db.schemas import RightsStatus, SceneSpec
from upsc_studio.graphics.rights import AssetRightsLedger


def _font(size: int, bold: bool = False) -> ImageFont.ImageFont:
    for path in (
        ["C:/Windows/Fonts/segoeuib.ttf", "C:/Windows/Fonts/arialbd.ttf"]
        if bold
        else ["C:/Windows/Fonts/segoeui.ttf", "C:/Windows/Fonts/arial.ttf"]
    ):
        if Path(path).exists():
            return ImageFont.truetype(path, size=size)
    return ImageFont.load_default()


class PublishingPackageBuilder:
    """Generates thumbnail, chapter timestamps, mind-map markdown, and publishing metadata."""

    def __init__(self, project_dir: Path, rights_ledger: AssetRightsLedger) -> None:
        self.project_dir = project_dir
        self.pub_dir = project_dir / "publishing"
        self.pub_dir.mkdir(parents=True, exist_ok=True)
        self.rights_ledger = rights_ledger

    def build_package(
        self,
        project_id: str,
        chapter_title: str,
        primary_papers: list[str],
        scenes: list[SceneSpec],
        specialist_key: str,
        specialist_profile: dict,
    ) -> dict:
        thumb_path = self._generate_thumbnail(project_id, chapter_title, primary_papers)
        mindmap_path = self._write_definitions_and_mindmap(chapter_title, specialist_key, specialist_profile)

        chapters_ts: list[dict] = []
        cursor = 0.0
        for s in scenes:
            mins, secs = divmod(int(cursor), 60)
            chapters_ts.append(
                {
                    "timestamp": f"{mins:02d}:{secs:02d}",
                    "scene_id": s.scene_id,
                    "title": s.section_title,
                }
            )
            cursor += s.estimated_duration_sec

        pkg = {
            "project_id": project_id,
            "video_title": f"{chapter_title} | Complete UPSC GS Analysis ({', '.join(primary_papers[:2])})",
            "thumbnail_path": str(thumb_path),
            "definitions_and_mindmap": str(mindmap_path),
            "chapters": chapters_ts,
            "tags": ["UPSC", "IAS", specialist_key, chapter_title],
            "auto_publish_blocked": True,
            "note": "User retains final publication approval.",
        }
        (self.pub_dir / "publishing_package.json").write_text(
            json.dumps(pkg, indent=2, ensure_ascii=False), encoding="utf-8"
        )
        return pkg

    def _generate_thumbnail(self, project_id: str, chapter_title: str, papers: list[str]) -> Path:
        w, h = 1280, 720
        img = Image.new("RGB", (w, h), color=(15, 23, 42))
        draw = ImageDraw.Draw(img)
        draw.rectangle([0, 0, w, 14], fill=(245, 158, 11))
        draw.text((72, 64), f"UPSC STUDIO  |  {' • '.join(papers[:2]).upper()}", fill=(245, 158, 11), font=_font(28, bold=True))

        y = 170
        for line in textwrap.wrap(chapter_title, width=26)[:3]:
            draw.text((72, y), line, fill=(248, 250, 252), font=_font(64, bold=True))
            y += 82

        draw.rounded_rectangle([72, 540, 620, 620], radius=12, fill=(30, 41, 59), outline=(56, 189, 248), width=3)
        draw.text((98, 562), "Prelims + Mains + Evidence-Backed", fill=(56, 189, 248), font=_font(28, bold=True))

        out_path = self.pub_dir / "thumbnail.png"
        img.save(out_path, format="PNG")
        self.rights_ledger.register_asset(
            project_id=project_id,
            asset_type="video_thumbnail",
            file_path=out_path,
            creator="UPSC Studio PublishingPackageBuilder",
            licence="ORIGINAL_GENERATED",
            rights_status=RightsStatus.ORIGINAL_GENERATED,
            attribution="Original thumbnail generated by UPSC Studio",
        )
        return out_path

    def _write_definitions_and_mindmap(
        self, chapter_title: str, specialist_key: str, profile: dict
    ) -> Path:
        terms = profile.get("key_terminology", [])
        hierarchy = profile.get("concept_hierarchy", [])
        lines = [
            f"# Key Definitions & Concept Mind Map — {chapter_title}",
            "",
            f"**Specialist Profile:** `{specialist_key}`",
            "",
            "## Core Terminology",
            *[f"- **{t}**: Defined in context of {chapter_title}." for t in terms],
            "",
            "## Concept Hierarchy (Mind Map)",
            "```mermaid",
            "flowchart TD",
            f'    ROOT["{chapter_title}"]',
        ]
        for idx, node in enumerate(hierarchy, start=1):
            lines.append(f'    N{idx}["{node}"]')
            lines.append(f"    ROOT --> N{idx}")
        lines.append("```")
        out_path = self.project_dir / "teaching" / "definitions_and_mindmap.md"
        out_path.write_text("\n".join(lines), encoding="utf-8")
        return out_path
